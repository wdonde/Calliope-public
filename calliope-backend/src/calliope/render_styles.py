def _row(r: sqlite3.Row | dict[str, Any]) -> dict[str, Any]:
    d = row_to_dict(r) if not isinstance(r, dict) else dict(r)
    d["workflows"] = {k: v for k, v in json.loads(d.pop("workflows_json") or "{}").items() if v}
    return d


def _workflows_by_prefix(conn: sqlite3.Connection, prefix: str) -> dict[str, int]:
    """'SDXL Nova Anime XL' -> {"0": id of '... – Text', "1": '... – 1 Referenz', "2": ...}."""
    out = {}
    for wid, name in conn.execute("SELECT id, name FROM workflows WHERE kind = 'image' AND name LIKE ?",
                                  (prefix + " –%",)):
        tail = name.split("–", 1)[1].strip().lower()
        n = "0" if tail.startswith("text") else tail[:1]
        if n in ("0", "1", "2"):
            out[n] = wid
    return out


def seed_presets() -> None:
    """Add the built-in styles once (an empty table); the user may edit or delete them."""
    conn = get_db(settings.db_path)
    try:
        if conn.execute("SELECT COUNT(*) FROM render_styles").fetchone()[0]:
            return
        for p in PRESETS:
            wfs = _workflows_by_prefix(conn, p["workflows"]) if p["workflows"] else {}
            if p["workflows"] and not wfs:
                continue  # SDXL set not installed
            conn.execute(
                "INSERT INTO render_styles (category, name, style_prompt, negative_prompt, workflows_json) "
                "VALUES (?, ?, ?, ?, ?)",
                (p["category"], p["name"], p["style_prompt"], p["negative_prompt"], json.dumps(wfs)))
        conn.commit()
    finally:
        conn.close()


def list_styles() -> list[dict[str, Any]]:
    conn = get_db(settings.db_path)
    try:
        return [_row(r) for r in conn.execute("SELECT * FROM render_styles ORDER BY category, name")]
    finally:
        conn.close()


def get_style(style_id: int | None) -> dict[str, Any] | None:
    if not style_id:
        return None
    conn = get_db(settings.db_path)
    try:
        r = conn.execute("SELECT * FROM render_styles WHERE id = ?", (style_id,)).fetchone()
        return _row(r) if r else None
    finally:
        conn.close()


def for_project(project_id: int | None) -> dict[str, Any] | None:
    if not project_id:
        return None
    conn = get_db(settings.db_path)
    try:
        r = conn.execute("SELECT render_style_id FROM projects WHERE id = ?", (project_id,)).fetchone()
    finally:
        conn.close()
    return get_style(r[0]) if r else None


def save_style(data: dict[str, Any], style_id: int | None = None) -> dict[str, Any]:
    fields = {k: data[k] for k in ("category", "name", "style_prompt", "negative_prompt") if k in data}
    if "workflows" in data:
        fields["workflows_json"] = json.dumps({str(k): v for k, v in (data["workflows"] or {}).items() if v})
    conn = get_db(settings.db_path)
    try:
        if style_id is None:
            cols = ", ".join(fields)
            cur = conn.execute(f"INSERT INTO render_styles ({cols}) VALUES ({', '.join('?' * len(fields))})",
                               tuple(fields.values()))
            style_id = cur.lastrowid
        elif fields:
            conn.execute(f"UPDATE render_styles SET {', '.join(f'{k} = ?' for k in fields)} WHERE id = ?",
                         (*fields.values(), style_id))
        conn.commit()
    finally:
        conn.close()
    style = get_style(style_id)
    if style is None:
        raise KeyError(style_id)
    return style


def delete_style(style_id: int) -> None:
    conn = get_db(settings.db_path)
    try:
        conn.execute("UPDATE projects SET render_style_id = NULL WHERE render_style_id = ?", (style_id,))
        conn.execute("DELETE FROM render_styles WHERE id = ?", (style_id,))
        conn.commit()
    finally:
        conn.close()


def workflow_for(style: dict[str, Any] | None, n_refs: int, role: str) -> int | None:
    """The style's workflow for this many references when it is still enabled, else the role's."""
    from calliope.workflow_roles import resolve

    wid = (style or {}).get("workflows", {}).get(str(min(n_refs, 2)))
    if wid:
        conn = get_db(settings.db_path)
        try:
            ok = conn.execute("SELECT 1 FROM workflows WHERE id = ? AND is_enabled = 1", (wid,)).fetchone()
        finally:
            conn.close()
        if ok:
            return wid
    return resolve(role)


def styled_prompt(prompt: str, style: dict[str, Any] | None, replace: tuple[str, ...] = ()) -> str:
    """The prompt led by the style's text; a built-in style text in front (``replace``) is swapped out."""
    text = (style or {}).get("style_prompt", "").strip().rstrip(".")
    if not text:
        return prompt
    for old in replace:
        if prompt.startswith(old):
            prompt = prompt[len(old):].lstrip(". ")
            break
    return prompt if prompt.startswith(text) else f"{text}. {prompt}"


def negative_values(inputs: list[dict[str, Any]], style: dict[str, Any] | None) -> dict[str, str]:
    """Input values for the workflow's negative prompt nodes from the style."""
    neg = (style or {}).get("negative_prompt", "").strip()
    if not neg:
        return {}
    return {str(i["nodeId"]): neg for i in inputs if i.get("role") == "negative"}
