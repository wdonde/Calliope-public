"""Render styles: how a project's pictures look.

A style belongs to a category (Anime, Manga, Webtoon, 3D, Realistic, ...)
and has its own name, so a category can hold any number of looks. It
carries a style text that leads every image prompt, a negative prompt, and
optionally a workflow per number of references ("0", "1", "2") -- e.g. the
SDXL Nova Anime XL set with IP-Adapter. Without a workflow the job keeps its
role (Settings > Workflows), so Klein styles are just text.

A project picks one style (projects.render_style_id); comic panels and the
project's asset renders then use it. No style = the built-in behaviour.
"""
from __future__ import annotations

import json
import sqlite3
from typing import Any

from calliope.config import settings
from calliope.db import get_db, row_to_dict

